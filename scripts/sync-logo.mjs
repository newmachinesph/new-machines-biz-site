// Converts design/logo/*.svg into TS data modules: strips the background rect,
// maps colours to currentColor, namespaces clipPath ids so Mark and Lockup can
// share a page. Re-run after `python -I design/logo/generate.py`.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, "../../design/logo");
const out = resolve(here, "../src/design-system/logo");
mkdirSync(out, { recursive: true });

const assets = [
  { file: "newmachines-mark-light.svg", name: "mark" },
  { file: "newmachines-lockup-light.svg", name: "lockup" },
];

for (const { file, name } of assets) {
  const svg = readFileSync(resolve(src, file), "utf8");
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
  if (!viewBox) throw new Error(`${file}: no viewBox`);
  const body = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replace(/<rect width="100%" height="100%"[^>]*\/>/, "")
    .replace(/#111111/gi, "currentColor")
    .replace(/id="h"/g, `id="nm-${name}-h"`)
    .replace(/url\(#h\)/g, `url(#nm-${name}-h)`)
    .trim();
  // Fail loudly if the generator's format drifts, instead of emitting a wrong or unsafe body.
  const leftovers = [
    [/<rect[^>]*100%/, "background rect"],
    [/#[0-9a-f]{3,8}\b/i, "hard-coded colour"],
    [/<script|<foreignObject|\son\w+=|href=/i, "unsafe content"],
    [new RegExp(`\\bid="(?!nm-${name}-)`), "un-namespaced id"],
  ].filter(([re]) => re.test(body)).map(([, what]) => what);
  if (leftovers.length) throw new Error(`${file}: ${leftovers.join(", ")} left in output`);
  const ts = `// Generated by scripts/sync-logo.mjs from design/logo/${file}. Do not edit.\n` +
    `export const ${name} = {\n  viewBox: ${JSON.stringify(viewBox)},\n  body: ${JSON.stringify(body)},\n} as const;\n`;
  writeFileSync(resolve(out, `${name}.data.ts`), ts);
  console.log(`wrote ${name}.data.ts (${body.length} chars)`);
}
